"""BDF bitmap fonts (ASCII 32..126) -> a C header of 1-bit glyph rows.

  tools/gen_font.py OUT.h NAME=FONT.bdf [NAME=FONT.bdf ...]

Each glyph is HEIGHT bytes, one per pixel row, bit 7 = the leftmost pixel (fonts up to 8 wide).
"""
import sys


def load_bdf(path):
    glyphs, w, h, ascent = {}, 0, 0, 0
    cur, bits, in_bitmap, bbx = None, [], False, None
    for line in open(path, encoding="latin-1"):
        p = line.split()
        if not p:
            continue
        if p[0] == "FONTBOUNDINGBOX":
            w, h = int(p[1]), int(p[2])
        elif p[0] == "FONT_ASCENT":
            ascent = int(p[1])
        elif p[0] == "ENCODING":
            cur = int(p[1])
        elif p[0] == "BBX":
            bbx = tuple(int(v) for v in p[1:5])
        elif p[0] == "BITMAP":
            in_bitmap, bits = True, []
        elif p[0] == "ENDCHAR":
            in_bitmap = False
            if cur is not None and 32 <= cur < 127:
                bw, bh, bx, by = bbx
                rows = [0] * h
                top = ascent - (by + bh)          # rows from the cell top
                nbytes = (bw + 7) // 8
                for i, hexrow in enumerate(bits):
                    v = int(hexrow, 16) >> (nbytes * 8 - 8) if nbytes > 1 else int(hexrow, 16)
                    r = top + i
                    if 0 <= r < h:
                        rows[r] = (v >> bx) & 0xFF if bx >= 0 else (v << -bx) & 0xFF
                glyphs[cur] = rows
        elif in_bitmap:
            bits.append(p[0])
    return w, h, glyphs


def main():
    out = ["/* Generated by tools/gen_font.py from Spleen (Copyright (c) 2018-2026 Frederic Cambus,",
           " * BSD-2-Clause, see THIRD_PARTY.md). Do not edit. */", "#pragma once", "#include <stdint.h>", ""]
    for arg in sys.argv[2:]:
        name, path = arg.split("=", 1)
        w, h, g = load_bdf(path)
        out.append(f"#define {name.upper()}_W {w}")
        out.append(f"#define {name.upper()}_H {h}")
        out.append(f"static const uint8_t {name}[95][{h}] = {{")
        for c in range(32, 127):
            rows = g.get(c, [0] * h)
            out.append("    {" + ", ".join(f"0x{v:02X}" for v in rows) + f"}},  /* {chr(c) if c != 92 else 'bs'} */")
        out.append("};")
        out.append("")
    open(sys.argv[1], "w", newline="\n").write("\n".join(out))


if __name__ == "__main__":
    main()

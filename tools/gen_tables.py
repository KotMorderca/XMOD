"""Generate engine/ft2_tables.c: the FT2 replayer tables.

The literal tables (arpeggio, sines, Amiga periods, MOD periods) are copied from ft2-clone's
src/ft2_tables.c (BSD-3-Clause, Olav Sorensen); the computed ones (exp2 log table, square-root
panning) use ft2-clone's formulas.

  tools/gen_tables.py FT2_CLONE_SRC/ft2_tables.c engine/ft2_tables.c
"""
import math
import re
import sys

NAMES = ["arpeggioTab", "autoVibSineTab", "vibratoTab", "amigaPeriodLUT", "modPeriods"]
OUT_NAMES = {"arpeggioTab": "ft2_arpeggio", "autoVibSineTab": "ft2_autovib_sine",
             "vibratoTab": "ft2_vibrato", "amigaPeriodLUT": "ft2_amiga_periods",
             "modPeriods": "ft2_mod_periods"}


def extract(src, name):
    m = re.search(r"const\s+(\w+)\s+" + name + r"\[([^\]]+)\]\s*=[^{]*\{(.*?)\};", src, re.S)
    if not m:
        raise SystemExit(f"{name} not found")
    body = re.sub(r"//[^\n]*", "", m.group(3))
    body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
    vals = [int(v, 0) for v in re.findall(r"-?(?:0x[0-9a-fA-F]+|\d+)", body)]
    return m.group(1), vals


def emit(ctype, name, vals, per=16):
    lines = [f"const {ctype} {name}[{len(vals)}] = {{"]
    for i in range(0, len(vals), per):
        lines.append("    " + ", ".join(str(v) for v in vals[i:i + per]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    src = open(sys.argv[1], encoding="latin-1").read()
    out = ["/* SPDX-License-Identifier: BSD-3-Clause */", "/* Generated by tools/gen_tables.py. Do not edit. */",
           "/* Literal tables from ft2-clone src/ft2_tables.c:",
           " * Copyright (c) 2016-2026, Olav Sorensen. BSD-3-Clause (see THIRD_PARTY.md). */",
           '#include "ft2_tables.h"', ""]
    for n in NAMES:
        ctype, vals = extract(src, n)
        out.append(emit(ctype, OUT_NAMES[n], vals))
        out.append("")
    log = [round(16777216.0 * 2.0 ** (i / 768.0)) for i in range(768)]
    out.append(emit("uint32_t", "ft2_log_tab", log, 8))
    out.append("")
    pan = [round(65536.0 * math.sqrt(i / 256.0)) for i in range(257)]
    out.append(emit("uint32_t", "ft2_sqrt_pan", pan, 12))
    out.append("")
    open(sys.argv[2], "w", newline="\n").write("\n".join(out))


if __name__ == "__main__":
    main()
